type Extra = Partial<ShipClass> & { sil: Silhouette; notes: string };

function S(
  id: string, nation: NationId, type: ShipType, name: string, year: number,
  length: number, beam: number, tons: number, speed: number, belt: number, deck: number,
  guns: MountDef[], aa: number, o: Extra,
): ShipClass {
  const merchant = isMerchantType(type);
  const hp = o.hp ?? Math.round(merchant ? 150 + tons * 0.07 : 250 + tons * 0.11);
  return {
    id, nation, type, name, year, length, beam, tons, speed, belt, deck, guns, aa,
    turn: TURN[type], accel: ACCEL[type], cost: 0, merchant,
    ...o,
    hp,
  };
}

