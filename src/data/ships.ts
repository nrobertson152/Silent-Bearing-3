export const CLASSES: Record<string, ShipClass> = Object.fromEntries(LIST.map((c) => [c.id, c]));

export function cls(id: string): ShipClass {
  const c = CLASSES[id];
  if (!c) throw new Error(`Unknown ship class: ${id}`);
  return c;
}

export function classesFor(nation: NationId): ShipClass[] {
  return LIST.filter((c) => c.nation === nation);
}

/** Classes the shipyard can build for a nation on a given date. */
export function purchasable(nation: NationId, year: number): ShipClass[] {
  return LIST.filter((c) => c.nation === nation && c.cost > 0 && c.year <= year + 0.01).sort(
    (a, b) => TYPE_VALUE[a.type] - TYPE_VALUE[b.type] || a.cost - b.cost,
  );
}
