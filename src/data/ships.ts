/** Seconds to raise steam from harbour readiness. */
export function steamTime(c: ShipClass): number {
  if (c.type === 'PT' || c.sub) return 60;
  if (c.type === 'DD' || c.type === 'DE' || c.type === 'TB') return 300;
  if (c.type === 'CA' || c.type === 'CL') return 480;
  return 720;
}

/** Ordering used for target value and lists. */
export const TYPE_VALUE: Record<ShipType, number> = {
  CV: 10, BB: 9, BC: 9, CVL: 8, CA: 7, CVE: 6, CL: 6, AP: 5, AO: 5, DD: 4, AK: 4, SS: 4, DE: 3, TB: 3,
  PT: 2, BASE: 6, BTY: 3,
};

export const isMerchantType = (t: ShipType) => t === 'AK' || t === 'AO' || t === 'AP';
export const isCarrierType = (t: ShipType) => t === 'CV' || t === 'CVL' || t === 'CVE';
export const isCapitalType = (t: ShipType) => t === 'BB' || t === 'BC' || t === 'CV' || t === 'CVL';
export const isStructureType = (t: ShipType) => t === 'BASE' || t === 'BTY';

/** "York-class heavy cruiser"; an airfield or a battery is just its name. */
export function classDesc(c: ShipClass): string {
  return isStructureType(c.type) ? c.name : `${c.name}-class ${TYPE_NAMES[c.type].toLowerCase()}`;
}

const tur = (g: string, n: number, ...ps: number[]): MountDef[] => ps.map((p) => ({ g, n, p }));
/** main-battery mounts on both beams */
const side = (g: string, n: number, ...ps: number[]): MountDef[] =>
  ps.flatMap((p) => [{ g, n, p, s: 1 }, { g, n, p, s: -1 }]);
/** secondary mounts on both beams */
const wing = (g: string, n: number, ...ps: number[]): MountDef[] =>
  ps.flatMap((p) => [{ g, n, p, s: 1, sec: true }, { g, n, p, s: -1, sec: true }]);

